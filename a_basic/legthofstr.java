package A_Besic.a2basic;

public class legthofstr {
    public static void main(String[] args) {
        
        String a = "Shivam jadhav";
        int length=0 ;
      for (char c : a.toCharArray()){
        System.out.print(c);
        length++;
      }
      System.out.println();
      System.out.println(length);


    }
}




